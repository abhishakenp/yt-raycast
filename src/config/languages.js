export const preferMixedEnglishBcp47FromPrompt = (prompt, pureBcp47Code) => {
  const pl = String(prompt || '').toLowerCase()
  const words = MIXED_ENGLISH_SLANG_KEYWORDS[pureBcp47Code]
  if (!words) return null
  for (const w of words) {
    if (pl.includes(w.toLowerCase())) return `${pureBcp47Code}-en`
  }
  return null
}

export const preferMixedEnglishBcp47FromSnippet = (snippet) => {
  const pl = String(snippet || '').toLowerCase()
  if (/\bhinglish\b/.test(pl)) return 'hinglish'
  if (/\bmanglish\b/.test(pl)) return 'ml-en'
  if (/\btanglish\b/.test(pl)) return 'ta-en'
  if (/\b(tenglish|teluglish)\b/.test(pl)) return 'te-en'
  if (/\bkanglish\b/.test(pl)) return 'kn-en'
  if (/\b(benglish|banglish)\b/.test(pl)) return 'bn-en'
  if (/\bgunglish\b/.test(pl)) return 'gu-en'
  if (/\bpunglish\b/.test(pl)) return 'pa-en'
  for (const [pureCode, words] of Object.entries(MIXED_ENGLISH_SLANG_KEYWORDS)) {
    for (const w of words) {
      if (pl.includes(w.toLowerCase())) return `${pureCode}-en`
    }
  }
  return null
}

export const isMixedEnglishIndicCode = (code) => {
  const c = String(code || '')
    .trim()
    .toLowerCase()
  return c === 'hinglish' || /^[a-z]{2,8}-en$/.test(c)
}

export const isRomanizedIndicCode = (code) => /^[a-z]{2,8}-latn$/i.test(String(code || '').trim())

// Any non-English locale we render via /api/translate: plain 2-char ISO, xx-latn
// (romanized), or the code-mixed variants (hinglish / xx-en). English is the only
// non-translatable value.
export const isTranslatableLocale = (code) => {
  const c = String(code || '')
    .trim()
    .toLowerCase()
  if (!c || c === 'en') return false
  return (
    /^[a-z]{2}$/.test(c) ||
    /^[a-z]{2,8}-latn$/.test(c) ||
    /^[a-z]{2,8}-en$/.test(c) ||
    c === 'hinglish'
  )
}

export const preferRomanizedBcp47FromSnippet = (snippet) => {
  const pl = String(snippet || '').toLowerCase()
  for (const l of INDIC_PURE_LANGUAGES) {
    const n = l.name.toLowerCase()
    if (
      pl.includes(`roman ${n}`) ||
      pl.includes(`romanized ${n}`) ||
      pl.includes(`romanised ${n}`) ||
      pl.includes(`${n} in roman`) ||
      pl.includes(`${n} in latin`) ||
      pl.includes(`${n} in english letter`) ||
      pl.includes(`${n} in english script`) ||
      pl.includes(`${n} in english alphabet`) ||
      pl.includes(`${l.code}-latn`)
    )
      return `${l.code}-latn`
  }
  return null
}

export const preferIndicBcp47FromRomanizedPrompt = (snippet) => {
  const words = new Set(
    String(snippet || '')
      .toLowerCase()
      .match(/\b[a-z][a-z']{1,}\b/g) || [],
  )
  if (words.size < 4) return null

  let best = null
  for (const [code, hints] of Object.entries(ROMANIZED_PROMPT_LANGUAGE_HINTS)) {
    const hits = hints.filter((hint) => words.has(hint))
    if (hits.length < 3) continue
    if (!best || hits.length > best.hits) best = { code, hits: hits.length }
  }
  return best ? best.code : null
}

